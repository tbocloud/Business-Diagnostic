// ─────────────────────────────────────────────────────────────
// QUESTION BANK
//
// Each question: options scored 0–100 (best → worst), plus plain-language
// notes for the dashboard. Every question automatically gets an
// "Other — type your own" choice and a "Skip" link in the UI.
//
// `show` makes the check adaptive: questions appear or disappear based on
// the client's stage, industry, team size, or earlier answers.
// ─────────────────────────────────────────────────────────────

// ── Visibility helpers ──────────────────────────────────────
const level = (...l: LevelId[]) => (c: Ctx) => !!c.profile.level && l.includes(c.profile.level);
const industry = (...i: IndustryId[]) => (c: Ctx) => !!c.profile.industry && i.includes(c.profile.industry);
const notIndustry = (...i: IndustryId[]) => (c: Ctx) => !c.profile.industry || !i.includes(c.profile.industry);
const solo = (c: Ctx) => c.profile.teamSize === 'solo';
const hasTeam = (c: Ctx) => c.profile.teamSize !== 'solo';
const answered = (qid: string, ...opts: string[]) => (c: Ctx) =>
  !!c.answers[qid]?.selected.some((o) => opts.includes(o));
const not = (f: (c: Ctx) => boolean) => (c: Ctx) => !f(c);
const all = (...fs: ((c: Ctx) => boolean)[]) => (c: Ctx) => fs.every((f) => f(c));

